"use server";

import { revalidatePath } from "next/cache";
import { createClient } from "@/lib/supabase/server";
import { applyMastery, applyMasteryDelta, gradePendingAnswers, recalcAttemptScore } from "@/lib/grading";

export async function createClass(
  name: string
): Promise<{ ok: true; id: string } | { ok: false; error: string }> {
  const trimmed = (name ?? "").trim();
  if (trimmed.length < 2 || trimmed.length > 60) {
    return { ok: false, error: "Class name must be 2–60 characters." };
  }

  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return { ok: false, error: "You are signed out. Log in again." };

  const { data: profile } = await supabase
    .from("profiles")
    .select("role")
    .eq("id", user.id)
    .single();
  if (profile?.role !== "teacher") {
    return { ok: false, error: "Only teachers can create classes." };
  }

  // join_code is generated by the database default
  const { data, error } = await supabase
    .from("classes")
    .insert({ teacher_id: user.id, name: trimmed })
    .select("id")
    .single();

  if (error || !data) {
    return { ok: false, error: error?.message ?? "Could not create the class. Try again." };
  }

  revalidatePath("/teacher");
  return { ok: true, id: data.id as string };
}




async function requireTeacher() {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return { error: "You are signed out. Log in again." as const };
  const { data: profile } = await supabase.from("profiles").select("role").eq("id", user.id).single();
  if (profile?.role !== "teacher") return { error: "Only teachers can do this." as const };
  return { supabase, user };
}

export async function overrideGrade(
  answerId: string,
  scorePercent: number,
  feedback: string
): Promise<{ ok: true } | { ok: false; error: string }> {
  const pct = Number(scorePercent);
  if (!Number.isFinite(pct) || pct < 0 || pct > 100) {
    return { ok: false, error: "Score must be between 0 and 100." };
  }

  const ctx = await requireTeacher();
  if ("error" in ctx) return { ok: false, error: ctx.error as string };
  const { supabase } = ctx;

  // RLS only returns answers from this teacher's classes
  const { data: ans } = await supabase
    .from("answers")
    .select("id, attempt_id, score, questions(topic)")
    .eq("id", answerId)
    .maybeSingle();
  if (!ans) return { ok: false, error: "Answer not found." };

  const { data: attempt } = await supabase
    .from("attempts")
    .select("student_id")
    .eq("id", ans.attempt_id)
    .maybeSingle();
  if (!attempt) return { ok: false, error: "Attempt not found." };

  const newScore = Math.round(pct) / 100;
  const update: Record<string, unknown> = {
    score: newScore,
    teacher_override: true,
    pending_review: false,
  };
  if (feedback.trim()) update.feedback = feedback.trim().slice(0, 600);

  const { data: updated, error } = await supabase
    .from("answers")
    .update(update)
    .eq("id", answerId)
    .select("id");
  if (error || !updated || updated.length === 0) {
    return { ok: false, error: "Could not save the grade." };
  }

  const q = Array.isArray(ans.questions) ? ans.questions[0] : ans.questions;
  const topic = (q as { topic?: string } | null)?.topic;
  if (topic) {
    if (ans.score === null) {
      await applyMastery(supabase, attempt.student_id as string, [{ topic, score: newScore }]);
    } else {
      await applyMasteryDelta(supabase, attempt.student_id as string, topic, newScore - Number(ans.score));
    }
  }
  await recalcAttemptScore(supabase, ans.attempt_id as string);

  revalidatePath("/teacher", "layout");
  revalidatePath("/student", "layout");
  return { ok: true };
}

export async function gradePendingAttempt(
  attemptId: string
): Promise<{ ok: true; graded: number; failed: number } | { ok: false; error: string }> {
  const ctx = await requireTeacher();
  if ("error" in ctx) return { ok: false, error: ctx.error as string };
  const { supabase } = ctx;

  const { data: attempt } = await supabase
    .from("attempts")
    .select("id, student_id")
    .eq("id", attemptId)
    .maybeSingle();
  if (!attempt) return { ok: false, error: "Attempt not found." };

  const { data: prof } = await supabase
    .from("profiles")
    .select("language")
    .eq("id", attempt.student_id)
    .maybeSingle();

  try {
    const res = await gradePendingAnswers(
      supabase,
      attemptId,
      attempt.student_id as string,
      (prof?.language as string) ?? "en"
    );
    revalidatePath("/teacher", "layout");
    revalidatePath("/student", "layout");
    return { ok: true, ...res };
  } catch (err) {
    console.error("[gradePendingAttempt]", err);
    return { ok: false, error: "Grading failed. Try again in a moment." };
  }
}